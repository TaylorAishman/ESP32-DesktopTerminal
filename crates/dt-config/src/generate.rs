//! Emit validated configuration as Rust source for `dt_core::config::Config`.

use core::fmt::Write as _;
use std::collections::BTreeMap;

use crate::api::{ApiConfig, AuthLocation};
use crate::secrets::SecretsConfig;
use crate::user::{Units, UserConfig};

/// Rust source defining `pub static CONFIG: dt_core::config::Config`.
///
/// The output contains the secrets, so it must only be written under the
/// build's `OUT_DIR`, never into the source tree.
pub fn generate(api: &ApiConfig, user: &UserConfig, secrets: &SecretsConfig) -> String {
    let mut o = String::new();
    o.push_str("// @generated by dt-config from config/*.toml. Do not edit; contains secrets.\n");
    o.push_str("pub static CONFIG: dt_core::config::Config = dt_core::config::Config {\n");
    let _ = writeln!(o, "    user_agent: {:?},", api.user_agent);
    let _ = writeln!(
        o,
        "    wifi: dt_core::config::WifiConfig {{ ssid: {:?}, password: dt_core::Secret::new({:?}) }},",
        secrets.wifi.ssid,
        secrets.wifi.password.expose()
    );
    let loc = &user.location;
    let units = match loc.units {
        Units::Metric => "Metric",
        Units::Imperial => "Imperial",
    };
    let _ = writeln!(
        o,
        "    location: dt_core::config::LocationConfig {{ name: {:?}, latitude: {:?}, longitude: {:?}, timezone: {:?}, units: dt_core::config::Units::{units} }},",
        loc.name, loc.latitude, loc.longitude, loc.timezone
    );

    o.push_str("    providers: &[\n");
    for (pid, p) in &api.providers {
        let location = match p.auth.send_as {
            AuthLocation::Query => "Query",
            AuthLocation::Header => "Header",
        };
        let key = secrets
            .api_keys
            .get(&p.auth.secret)
            .map(|s| s.expose())
            .unwrap_or("");
        let _ = writeln!(o, "        dt_core::config::ProviderConfig {{");
        let _ = writeln!(
            o,
            "            id: {pid:?}, name: {:?}, base_url: {:?}, host: {:?},",
            p.name,
            p.base_url,
            host_of(&p.base_url)
        );
        let _ = writeln!(
            o,
            "            auth: dt_core::config::AuthConfig {{ location: dt_core::config::AuthLocation::{location}, name: {:?}, secret_name: {:?}, key: dt_core::Secret::new({key:?}) }},",
            p.auth.name, p.auth.secret
        );
        o.push_str("            limits: &[");
        for l in &p.limits {
            let _ = write!(
                o,
                "dt_core::api::Limit {{ calls: {}, per: dt_core::api::Period::{:?} }}, ",
                l.calls, l.per
            );
        }
        o.push_str("],\n");
        let _ = writeln!(
            o,
            "            utilisation: {:?}, timeout_ms: {},",
            p.utilisation, p.timeout_ms
        );
        o.push_str("            endpoints: &[\n");
        for (eid, e) in &p.endpoints {
            let _ = writeln!(
                o,
                "                dt_core::config::EndpointConfig {{ id: {eid:?}, path: {:?}, params: {}, weight: {}, min_interval_s: {}, max_staleness_s: {}, max_response_bytes: {}, off_hours_interval_s: {:?} }},",
                e.path,
                params(&e.params),
                e.weight,
                e.min_interval_s,
                e.max_staleness_s,
                e.max_response_bytes,
                e.off_hours_interval_s
            );
        }
        o.push_str("            ],\n        },\n");
    }
    o.push_str("    ],\n");

    o.push_str("    topics: &[\n");
    for t in &user.news.topics {
        let _ = writeln!(
            o,
            "        dt_core::config::TopicConfig {{ title: {:?}, params: {} }},",
            t.title,
            params(&t.params)
        );
    }
    o.push_str("    ],\n    instruments: &[\n");
    for i in &user.finance.instruments {
        let _ = writeln!(
            o,
            "        dt_core::config::InstrumentConfig {{ label: {:?}, symbol: {:?} }},",
            i.label, i.symbol
        );
    }
    o.push_str("    ],\n};\n");
    o
}

fn params(p: &BTreeMap<String, String>) -> String {
    let items: Vec<String> = p.iter().map(|(k, v)| format!("({k:?}, {v:?})")).collect();
    format!("&[{}]", items.join(", "))
}

/// "https://api.example.com/v1" -> "api.example.com".
pub fn host_of(url: &str) -> &str {
    let rest = url.split_once("://").map_or(url, |(_, r)| r);
    rest.split(['/', ':', '?']).next().unwrap_or(rest)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{parse_api, parse_secrets, parse_user};

    #[test]
    fn hosts() {
        assert_eq!(host_of("https://newsapi.org/v2"), "newsapi.org");
        assert_eq!(
            host_of("https://api.openweathermap.org/data/2.5"),
            "api.openweathermap.org"
        );
        assert_eq!(host_of("https://x.io:8443/a"), "x.io");
    }

    #[test]
    fn escapes_strings() {
        let api = parse_api(include_str!("../../../config/api.toml")).unwrap();
        let user = parse_user(
            "u",
            &include_str!("../../../config/user.example.toml")
                .replace("\"New York\"", r#""Quote \" and \\ back""#),
        )
        .unwrap();
        let secrets =
            parse_secrets("s", include_str!("../../../config/secrets.example.toml")).unwrap();
        let src = generate(&api, &user, &secrets);
        assert!(src.contains(r#"name: "Quote \" and \\ back""#), "{src}");
        assert!(src.contains("pub static CONFIG"));
    }
}
