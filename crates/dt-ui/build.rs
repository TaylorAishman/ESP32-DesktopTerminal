//! Rasterise `assets/icons/*.svg` to 1-bit bitmaps at fixed sizes and
//! generate the `Icon` enum (see assets/icons/README.md).

use std::{env, fmt::Write as _, fs, path::PathBuf};

/// Pixel sizes every icon is rendered at.
const SIZES: [u32; 6] = [16, 24, 32, 48, 64, 96];

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../assets/icons");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "svg"))
        .collect();
    files.sort();

    let opts = resvg::usvg::Options::default();
    let mut out =
        String::from("// @generated by dt-ui/build.rs from assets/icons. Do not edit.\n\n");
    let mut variants = Vec::new();
    let mut data = String::new();
    for path in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let stem = path.file_stem().unwrap().to_str().unwrap();
        let variant = camel(stem);
        let svg = fs::read(path).unwrap();
        let tree = resvg::usvg::Tree::from_data(&svg, &opts)
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let _ = writeln!(
            data,
            "const {}: [Bitmap; {}] = [",
            stem.to_uppercase(),
            SIZES.len()
        );
        for size in SIZES {
            let bytes = rasterise(&tree, size);
            let _ = writeln!(data, "    Bitmap {{ size: {size}, bits: &{bytes:?} }},");
        }
        data.push_str("];\n\n");
        variants.push((variant, stem.to_uppercase(), stem.to_owned()));
    }

    let _ = writeln!(out, "/// Every icon in assets/icons.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum Icon {{");
    for (v, _, stem) in &variants {
        let _ = writeln!(out, "    /// assets/icons/{stem}.svg\n    {v},");
    }
    out.push_str("}\n\nimpl Icon {\n");
    let _ = writeln!(
        out,
        "    pub const ALL: [Icon; {}] = [{}];\n",
        variants.len(),
        variants
            .iter()
            .map(|(v, ..)| format!("Icon::{v}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    out.push_str("    fn bitmaps(self) -> &'static [Bitmap] {\n        match self {\n");
    for (v, c, _) in &variants {
        let _ = writeln!(out, "            Icon::{v} => &{c},");
    }
    out.push_str("        }\n    }\n}\n\n");
    let _ = writeln!(
        out,
        "/// Sizes every icon is available in.\npub const SIZES: [u32; {}] = {SIZES:?};\n",
        SIZES.len()
    );
    out.push_str(&data);

    fs::write(
        PathBuf::from(env::var("OUT_DIR").unwrap()).join("icons.rs"),
        out,
    )
    .unwrap();
}

/// Render at `size`×`size` and pack to 1 bit per pixel, rows padded to whole
/// bytes, MSB first, set = black.
fn rasterise(tree: &resvg::usvg::Tree, size: u32) -> Vec<u8> {
    let mut pixmap = resvg::tiny_skia::Pixmap::new(size, size).unwrap();
    let s = tree.size();
    let scale = size as f32 / s.width().max(s.height());
    resvg::render(
        tree,
        resvg::tiny_skia::Transform::from_scale(scale, scale),
        &mut pixmap.as_mut(),
    );
    let row = size.div_ceil(8) as usize;
    let mut out = vec![0u8; row * size as usize];
    for y in 0..size as usize {
        for x in 0..size as usize {
            let alpha = pixmap.pixel(x as u32, y as u32).map_or(0, |p| p.alpha());
            if alpha >= 128 {
                out[y * row + x / 8] |= 0x80 >> (x % 8);
            }
        }
    }
    out
}

fn camel(stem: &str) -> String {
    stem.split(['_', '-'])
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}
